package com.jsf.pointvalidation.util;

public class AreaChecker {

    /**
     * Проверяет попадание точки в область согласно варианту
     * Область состоит из:
     * 1. Прямоугольник в 1-й четверти (x: 0 до R/2, y: 0 до R)
     * 2. Треугольник в 4-й четверти (x: 0 до R/2, y: 0 до -R/2)
     * 3. Четверть круга во 2-й четверти (радиус R/2)
     */
    public static boolean checkHit(double x, double y, double r) {
        // Проверка прямоугольника в 1-й четверти (x >= 0, y >= 0)
        if (x >= 0 && y >= 0) {
            return x <= r / 2 && y <= r;
        }

        // Проверка четверти круга во 2-й четверти (x <= 0, y >= 0)
        if (x <= 0 && y >= 0) {
            return (x * x + y * y) <= (r / 2) * (r / 2);
        }

        // Проверка треугольника в 4-й четверти (x >= 0, y <= 0)
        if (x >= 0 && y <= 0) {
            return x <= r / 2 && y >= -r / 2 && (y >= -x - r / 2);
        }

        // Точка в 3-й четверти - не входит в область
        return false;
    }
}
